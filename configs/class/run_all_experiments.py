#!/usr/bin/env python3
"""
Run every gem5 class experiment configuration and store trimmed stats outputs.

Each YAML under configs/class/experiments/ is executed via run.sh (with
parse_stats suppressed). After every successful run the script captures the
summary emitted by configs/class/parse_stats.py and writes it to
configs/class/result/<experiment>/<config>.stats.

Usage:
    python3 configs/class/run_all_experiments.py

Optional flags are available; run with --help for details.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional


REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_EXPERIMENTS_DIR = REPO_ROOT / "configs" / "class" / "experiments"
DEFAULT_RESULT_DIR = REPO_ROOT / "configs" / "class" / "result"
DEFAULT_RUN_SCRIPT = REPO_ROOT / "configs" / "class" / "run.sh"
DEFAULT_PARSE_SCRIPT = REPO_ROOT / "configs" / "class" / "parse_stats.py"
DEFAULT_STATS_PATH = REPO_ROOT / "m5out" / "stats.txt"
DEFAULT_STATS_COPY_SUFFIX = ".stats.txt"


@dataclass
class RunResult:
    config: Path
    output_file: Path
    succeeded: bool
    message: str


def discover_configs(experiments_dir: Path) -> List[Path]:
    return sorted(experiments_dir.rglob("*.yaml"))


def ensure_path_exists(path: Path) -> Path:
    if not path.exists():
        raise FileNotFoundError(f"Required script not found: {path}")
    return path


def build_cli() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run all gem5 class experiments and store trimmed stats summaries."
    )
    parser.add_argument(
        "--experiments-dir",
        type=Path,
        default=DEFAULT_EXPERIMENTS_DIR,
        help="Directory containing experiment YAML files (default: configs/class/experiments/)",
    )
    parser.add_argument(
        "--result-dir",
        type=Path,
        default=DEFAULT_RESULT_DIR,
        help="Directory to write summary files (default: configs/class/result/)",
    )
    parser.add_argument(
        "--run-script",
        type=Path,
        default=DEFAULT_RUN_SCRIPT,
        help="Path to run.sh (default: configs/class/run.sh)",
    )
    parser.add_argument(
        "--parse-script",
        type=Path,
        default=DEFAULT_PARSE_SCRIPT,
        help="Path to parse_stats.py (default: configs/class/parse_stats.py)",
    )
    parser.add_argument(
        "--stats-path",
        type=Path,
        default=DEFAULT_STATS_PATH,
        help="Path to stats.txt generated by gem5 (default: m5out/stats.txt)",
    )
    parser.add_argument(
        "--override-cmd",
        type=str,
        help="Override workload command passed to run.sh.",
    )
    parser.add_argument(
        "--skip-existing",
        action="store_true",
        help="Skip configs when a summary file already exists.",
    )
    parser.add_argument(
        "--copy-stats",
        action="store_true",
        help=(
            "After a successful run, copy the raw stats.txt to the result "
            "folder (name: <config>.stats.txt)."
        ),
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Print detailed progress for each configuration.",
    )
    return parser


def run_config(
    config_path: Path,
    *,
    run_script: Path,
    parse_script: Path,
    stats_path: Path,
    result_root: Path,
    experiments_root: Path,
    override_cmd: Optional[str],
    copy_stats: bool,
    verbose: bool,
) -> RunResult:
    rel_experiment = config_path.relative_to(experiments_root)
    output_dir = result_root / rel_experiment.parent
    output_dir.mkdir(parents=True, exist_ok=True)
    output_file = output_dir / (config_path.stem + ".stats")

    if stats_path.exists():
        try:
            stats_path.unlink()
        except OSError as exc:
            return RunResult(
                config_path,
                output_file,
                False,
                f"Failed to remove stale stats file {stats_path}: {exc}",
            )

    env = os.environ.copy()
    env["SKIP_PARSE_STATS"] = "1"

    run_args = ["bash", str(run_script), str(config_path.relative_to(REPO_ROOT))]
    if override_cmd:
        run_args.append(override_cmd)

    if verbose:
        print(f"[run] {' '.join(run_args)}")

    try:
        subprocess.run(run_args, cwd=REPO_ROOT, env=env, check=True)
    except subprocess.CalledProcessError as exc:
        failure_msg = (
            f"gem5 run failed (exit code {exc.returncode}) for {config_path.relative_to(REPO_ROOT)}"
        )
        output_file.write_text(failure_msg + "\n")
        return RunResult(config_path, output_file, False, failure_msg)

    if not stats_path.exists():
        message = f"Stats file not produced at {stats_path}"
        output_file.write_text(message + "\n")
        return RunResult(config_path, output_file, False, message)

    if copy_stats:
        stats_copy_path = output_dir / (config_path.stem + DEFAULT_STATS_COPY_SUFFIX)
        try:
            stats_copy_path.write_bytes(stats_path.read_bytes())
        except OSError as exc:
            message = f"Failed to copy stats to {stats_copy_path}: {exc}"
            output_file.write_text(message + "\n")
            return RunResult(config_path, output_file, False, message)

    parse_args = ["python3", str(parse_script), "--stats", str(stats_path)]
    if verbose:
        print(f"[parse] {' '.join(parse_args)}")
    try:
        summary = subprocess.run(
            parse_args,
            cwd=REPO_ROOT,
            check=True,
            capture_output=True,
            text=True,
        )
    except subprocess.CalledProcessError as exc:
        message = (
            f"parse_stats failed (exit code {exc.returncode}) for "
            f"{config_path.relative_to(REPO_ROOT)}"
        )
        output_file.write_text(
            message
            + "\n\nstdout:\n"
            + exc.stdout
            + "\n\nstderr:\n"
            + exc.stderr
        )
        return RunResult(config_path, output_file, False, message)

    header = f"# Summary for {config_path.relative_to(REPO_ROOT)}\n"
    output_file.write_text(header + summary.stdout.strip() + "\n")
    return RunResult(config_path, output_file, True, "ok")


def resolve_path(base: Path, target: Path) -> Path:
    return target if target.is_absolute() else (base / target)


def main(argv: List[str]) -> int:
    parser = build_cli()
    args = parser.parse_args(argv)

    experiments_dir = resolve_path(REPO_ROOT, args.experiments_dir)
    result_dir = resolve_path(REPO_ROOT, args.result_dir)
    run_script = ensure_path_exists(resolve_path(REPO_ROOT, args.run_script))
    parse_script = ensure_path_exists(resolve_path(REPO_ROOT, args.parse_script))
    stats_path = resolve_path(REPO_ROOT, args.stats_path)

    if not experiments_dir.is_dir():
        parser.error(f"Experiments directory not found: {experiments_dir}")

    result_dir.mkdir(parents=True, exist_ok=True)

    configs = discover_configs(experiments_dir)
    if not configs:
        parser.error(f"No YAML configs found under {experiments_dir}")

    if args.verbose:
        print(f"Discovered {len(configs)} configs under {experiments_dir}")

    results: List[RunResult] = []
    for config in configs:
        rel_experiment = config.relative_to(experiments_dir)
        output_path = result_dir / rel_experiment.parent / (config.stem + ".stats")
        if args.skip_existing and output_path.exists():
            if args.verbose:
                print(f"[skip] {rel_experiment} (exists)")
            continue

        print(f"Running {rel_experiment} ...")
        result = run_config(
            config,
            run_script=run_script,
            parse_script=parse_script,
            stats_path=stats_path,
            result_root=result_dir,
            experiments_root=experiments_dir,
            override_cmd=args.override_cmd,
            copy_stats=args.copy_stats,
            verbose=args.verbose,
        )
        results.append(result)
        status = "OK" if result.succeeded else "FAIL"
        print(f"  -> {status}. Summary: {result.output_file.relative_to(REPO_ROOT)}")

    failures = [r for r in results if not r.succeeded]
    print("\nCompleted runs.")
    print(f"  Successful: {len(results) - len(failures)}")
    print(f"  Failed: {len(failures)}")
    if failures:
        print("Failed configs:")
        for entry in failures:
            rel = entry.config.relative_to(REPO_ROOT)
            print(f"  - {rel}: {entry.message}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
